async def test_a_later_batch_closes_the_trace(
    tenants: tuple[Tenant, Tenant], client: AsyncClient
) -> None:
    """The reason traces upsert rather than DO NOTHING.

    The SDK sends a trace when the run starts and again when it ends. Under
    ON CONFLICT DO NOTHING the second write is discarded and ended_at is never
    recorded - so the merge is what makes the close observable at all.
    """
    a, _ = tenants
    t0 = _now()
    trace_id = uuid4()

    await client.post(
        "/v1/ingest",
        json={
            "traces": [
                {
                    "id": str(trace_id),
                    "name": "long-run",
                    "user_id": "u-1",
                    "started_at": t0.isoformat(),
                    "metadata": {"env": "prod"},
                }
            ]
        },
        headers=a.headers,
    )
    await client.post(
        "/v1/ingest",
        json={
            "traces": [
                {
                    "id": str(trace_id),
                    "ended_at": (t0 + timedelta(seconds=5)).isoformat(),
                    "metadata": {"region": "eu"},
                }
            ]
        },
        headers=a.headers,
    )

    async with tenant_session(a.project_id) as session:
        row = (
            await session.execute(
                text(
                    "SELECT name, user_id, ended_at IS NOT NULL, "
                    "metadata->>'env', metadata->>'region' FROM traces WHERE id = :t"
                ),
                {"t": trace_id},
            )
        ).first()

    assert row is not None
    name, user_id, closed, env, region = row
    assert closed is True, "ended_at must be recorded by the second batch"
    assert name == "long-run", "a partial batch must not blank an existing name"
    assert user_id == "u-1"
    assert (env, region) == ("prod", "eu"), "metadata merges rather than replacing"


