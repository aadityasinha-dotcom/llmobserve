async def test_observation_fields_land_in_the_right_columns(
    tenants: tuple[Tenant, Tenant], client: AsyncClient
) -> None:
    """Exercises the OTel aliases, the generated column, and server-side cost."""
    a, _ = tenants
    t0 = _now()
    obs_id = uuid4()

    response = await client.post(
        "/v1/ingest",
        json={
            "traces": [
                {
                    "id": str(uuid4()),
                    "started_at": t0.isoformat(),
                    "observations": [
                        {
                            "id": str(obs_id),
                            "type": "generation",
                            "gen_ai.request.model": "claude-opus-5-20260115",
                            "gen_ai.system": "anthropic",
                            "gen_ai.usage.input_tokens": 1000,
                            "gen_ai.usage.output_tokens": 500,
                            "start_time": t0.isoformat(),
                            "end_time": (t0 + timedelta(milliseconds=1234)).isoformat(),
                            "input": {"messages": [{"role": "user", "content": "hi"}]},
                            "output": {"text": "hello"},
                        }
                    ],
                }
            ]
        },
        headers=a.headers,
    )
    assert response.status_code == 202

    async with tenant_session(a.project_id) as session:
        row = (
            await session.execute(
                text(
                    "SELECT model, provider, prompt_tokens, completion_tokens, "
                    "total_tokens, cost_usd, latency_ms, type, input->>'messages' IS NOT NULL "
                    "FROM observations WHERE id = :i"
                ),
                {"i": obs_id},
            )
        ).first()

    assert row is not None
    model, provider, prompt, completion, total, cost, latency, type_, has_input = row
    assert model == "claude-opus-5-20260115"
    assert provider == "anthropic"
    assert (prompt, completion) == (1000, 500)
    assert total == 1500, "total_tokens is generated by the database"
    assert cost == Decimal("0.01750000"), "cost computed server-side at write time"
    assert latency == 1234, "latency derived from the timestamps"
    assert type_ == "generation"
    assert has_input is True


