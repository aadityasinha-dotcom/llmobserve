async def test_out_of_window_observations_are_rejected_individually(
    tenants: tuple[Tenant, Tenant], client: AsyncClient
) -> None:
    """One skewed clock must not cost the rest of the batch."""
    a, _ = tenants
    t0 = _now()
    good, too_old, too_new = uuid4(), uuid4(), uuid4()

    response = await client.post(
        "/v1/ingest",
        json={
            "traces": [
                {
                    "id": str(uuid4()),
                    "name": "clock-skew",
                    "started_at": t0.isoformat(),
                    "observations": [
                        {"id": str(good), "start_time": t0.isoformat()},
                        {"id": str(too_old), "start_time": (t0 - timedelta(days=30)).isoformat()},
                        {"id": str(too_new), "start_time": (t0 + timedelta(days=10)).isoformat()},
                    ],
                }
            ]
        },
        headers=a.headers,
    )

    assert response.status_code == 202, "a bad timestamp is not a bad request"
    assert response.json() == {
        "accepted_traces": 1,
        "accepted_observations": 1,
        "accepted_scores": 0,
        "rejected_observations": 2,
        "rejected_scores": 0,
    }

    assert (
        await _scalar(a.project_id, "SELECT count(*) FROM observations WHERE id = :i", i=good) == 1
    )
    for rejected in (too_old, too_new):
        assert (
            await _scalar(
                a.project_id, "SELECT count(*) FROM observations WHERE id = :i", i=rejected
            )
            == 0
        )

    assert await _scalar(a.project_id, "SELECT count(*) FROM traces") == 1, (
        "the trace is still recorded even though its observations were dropped"
    )


async def test_nothing_reaches_the_default_partition(
    tenants: tuple[Tenant, Tenant], client: AsyncClient
) -> None:
    """The whole point of the window.

    A row in observations_default permanently costs its day a partition:
    ensure_observations_partitions() warns and skips any day whose rows are
    already stranded, so every later write for that day lands in DEFAULT too and
    stops being pruned.
    """
    a, _ = tenants
    t0 = _now()

    await client.post(
        "/v1/ingest",
        json={
            "traces": [
                {
                    "id": str(uuid4()),
                    "observations": [
                        {"id": str(uuid4()), "start_time": (t0 + delta).isoformat()}
                        for delta in (
                            timedelta(0),
                            timedelta(days=-365),
                            timedelta(days=365),
                            timedelta(days=-8),
                            timedelta(days=2),
                        )
                    ],
                }
            ]
        },
        headers=a.headers,
    )

    stranded = await _scalar(
        a.project_id,
        "SELECT count(*) FROM observations WHERE tableoid = 'observations_default'::regclass",
    )
    assert stranded == 0


@pytest.mark.parametrize(
    ("label", "delta"),
    [
        ("oldest accepted", timedelta(days=-6, hours=-23)),
        ("newest accepted", timedelta(hours=23)),
        ("now", timedelta(0)),
    ],
)
async def test_accepted_timestamps_route_to_a_named_partition(
    tenants: tuple[Tenant, Tenant], client: AsyncClient, label: str, delta: timedelta
) -> None:
    """Everything inside the accepted window must have a partition waiting.

    This is the invariant that ties app.config to migration 0003: the accepted
    range must be a strict subset of the partitioned range. If someone widens
    ingest_max_event_age_days without widening DAYS_BEHIND, this fails.
    """
    a, _ = tenants
    obs_id = uuid4()

    response = await client.post(
        "/v1/ingest",
        json={
            "traces": [
                {
                    "id": str(uuid4()),
                    "observations": [
                        {"id": str(obs_id), "start_time": (_now() + delta).isoformat()}
                    ],
                }
            ]
        },
        headers=a.headers,
    )
    assert response.json()["rejected_observations"] == 0, f"{label} should be accepted"

    partition = await _scalar(
        a.project_id,
        "SELECT tableoid::regclass::text FROM observations WHERE id = :i",
        i=obs_id,
    )
    assert partition is not None
    assert partition != "observations_default", f"{label} was stranded in DEFAULT"
    assert partition.startswith("observations_p"), partition


