async def test_a_flat_observation_without_a_trace_id_is_kept(
    tenants: tuple[Tenant, Tenant], client: AsyncClient
) -> None:
    """Unattributable, but derived deterministically so retries do not multiply.

    The trace id is taken from the observation's own id. Minting a fresh uuid
    per request would create a new placeholder trace on every redelivery.

    start_time is sent explicitly because the observations primary key is
    (project_id, id, started_at) - the partition key has to be in it. A client
    that omits the timestamp gets a server-stamped one, which differs per
    request and therefore defeats deduplication. That obligation is on the SDK
    and is documented on the Observation model; it is not something the server
    can paper over.
    """
    a, _ = tenants
    obs_id = uuid4()
    body: dict[str, Any] = {
        "events": [
            {
                "id": str(obs_id),
                "type": "span",
                "name": "orphan",
                "start_time": _now().isoformat(),
            }
        ]
    }

    for _ in range(2):
        response = await client.post("/v1/ingest", json=body, headers=a.headers)
        assert response.status_code == 202

    assert await _scalar(a.project_id, "SELECT count(*) FROM observations") == 1
    assert await _scalar(a.project_id, "SELECT count(*) FROM traces") == 1
    assert (
        await _scalar(a.project_id, "SELECT trace_id FROM observations WHERE id = :i", i=obs_id)
        == obs_id
    ), "the derived trace id is the observation's own, so it is stable"


async def test_an_observation_without_a_timestamp_cannot_deduplicate(
    tenants: tuple[Tenant, Tenant], client: AsyncClient
) -> None:
    """Pins the known limit of idempotency rather than pretending it is absent.

    started_at is the partition key and Postgres requires it in every unique
    constraint, so it is part of the identity of a row. Without a client-supplied
    timestamp the server stamps its own, and a retry is genuinely a different
    row. Documented on the Observation model as an SDK obligation; asserted here
    so that a future change making retries silently duplicate *with* timestamps
    would still be caught by the test above.
    """
    a, _ = tenants
    obs_id = uuid4()
    body: dict[str, Any] = {"events": [{"id": str(obs_id), "type": "span", "name": "no-timestamp"}]}

    for _ in range(2):
        assert (await client.post("/v1/ingest", json=body, headers=a.headers)).status_code == 202

    assert await _scalar(a.project_id, "SELECT count(*) FROM observations") == 2


