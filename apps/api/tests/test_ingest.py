"""POST /v1/ingest: persistence, idempotency, and the partition window.

Tenant isolation is covered separately in test_tenant_isolation.py. What is
under test here is that a batch survives the round trip intact - that the
OpenTelemetry field aliases land in the right columns, that cost is computed by
the server and not taken from the client, that a retry does not duplicate, and
that a timestamp outside the partitioned range is refused rather than stranded.
"""

from datetime import UTC, datetime, timedelta
from decimal import Decimal
from typing import Any
from uuid import UUID, uuid4

import pytest
from httpx import AsyncClient
from sqlalchemy import text

from tests.conftest import Tenant, tenant_session


def _now() -> datetime:
    # Whole seconds: the payload round-trips through ISO-8601 and the assertions
    # below compare against what was sent.
    return datetime.now(UTC).replace(microsecond=0)


async def _scalar(project_id: UUID, sql: str, **params: Any) -> Any:
    async with tenant_session(project_id) as session:
        return await session.scalar(text(sql), params)


